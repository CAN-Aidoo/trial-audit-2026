"""Score Step 1 (screening) of the blinded human re-check on its own, before Step 2 is done.

Usage: python3 human/score_screening.py
Writes human/screening_agreement.json, screening_discrepancies.csv, macros_human_screening.tex.
Locks the screening sheet (screening.sha256.json): later runs refuse if it changed, so the reported
agreement is the pre-resolution one. score_human.py later scores both steps together.
"""
import csv
import glob
import hashlib
import json
import os

from openpyxl import load_workbook

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H = os.path.join(ROOT, "human")
final = {r["id"]: r for r in (json.load(open(f)) for f in glob.glob(os.path.join(ROOT, "data/extract/*.json")))}
path = os.path.join(H, "1_screening.xlsx")
digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
lock = os.path.join(H, "screening.sha256.json")
if os.path.exists(lock) and json.load(open(lock))["sha256"] != digest:
    raise SystemExit("Screening sheet changed since it was scored; report the original agreement.")

ws = load_workbook(path, data_only=True).active
vals = [["" if v is None else str(v).strip() for v in r] for r in ws.iter_rows(values_only=True)]
rows = [dict(zip(vals[0], r)) for r in vals[1:] if r[0]]
assert all(r["id"] in final for r in rows), "unknown paper id"


def yn(v):
    v = v.lower()
    return True if v in ("y", "yes") else False if v in ("n", "no") else None


assert all(yn(r["include (Y/N)"]) is not None for r in rows), "screening incomplete"
if not os.path.exists(lock):
    json.dump({"sha256": digest, "file": "1_screening.xlsx"}, open(lock, "w"), indent=1)

disc = []
pairs = [(final[r["id"]]["include"], yn(r["include (Y/N)"])) for r in rows]
n = len(pairs)
agree = sum(a == b for a, b in pairs)
p1, p2 = sum(a for a, _ in pairs) / n, sum(b for _, b in pairs) / n
pe = p1 * p2 + (1 - p1) * (1 - p2)
kappa = (agree / n - pe) / (1 - pe) if pe < 1 else float("nan")
for r in rows:
    f = final[r["id"]]
    if f["include"] != yn(r["include (Y/N)"]):
        disc.append(dict(id=r["id"], field="include", final=f"{f['include']} ({f['exclude_reason']})",
                         human=f"{r['include (Y/N)']} ({r['reason (I1/I2/I3 failed, or meets I1-I3)']})"))

REP = [("ci_or_errorbars", "ci_or_errorbars (Y/N)"), ("sig_test", "sig_test (Y/N)"),
       ("seeds_reported", "seeds_reported (Y/N)"), ("success_defined", "success_defined (Y/N)"),
       ("randomized_init", "randomized_init (yes/no/unclear)")]
rep = {k: [0, 0] for k, _ in REP}
for r in rows:
    f = final[r["id"]]
    if not (f["include"] and yn(r["include (Y/N)"])):
        continue
    for k, col in REP:
        a = f["reporting"][k] if k == "randomized_init" else bool(f["reporting"][k])
        b = r[col].lower() if k == "randomized_init" else yn(r[col])
        rep[k][1] += 1
        rep[k][0] += a == b
        if a != b:
            disc.append(dict(id=r["id"], field="reporting." + k, final=a, human=r[col]))

both = sum(1 for a, b in pairs if a and b)
cells = sum(t for _, t in rep.values())
cell_agree = sum(a for a, _ in rep.values())
mins = [float(r["minutes spent"]) for r in rows if r["minutes spent"]]
out = dict(papers=n, include_agree=agree, include_kappa=kappa, both_included=both,
           reporting_agreement={k: (a / t if t else None, t) for k, (a, t) in rep.items()},
           reporting_cells_agree=cell_agree, reporting_cells=cells, minutes_total=sum(mins),
           discrepancies=len(disc), sha256=digest)
json.dump(out, open(os.path.join(H, "screening_agreement.json"), "w"), indent=1)
with open(os.path.join(H, "screening_discrepancies.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=["id", "field", "final", "human", "resolution"])
    w.writeheader()
    w.writerows(disc)
M = dict(HumScrPapers=n, HumScrAgree=agree, HumScrKappa=f"{kappa:.2f}", HumScrBoth=both,
         HumRepCellsAgree=cell_agree, HumRepCells=cells, HumScrMinutes=f"{sum(mins):.0f}")
with open(os.path.join(H, "macros_human_screening.tex"), "w") as fh:
    fh.write("% generated by human/score_screening.py -- do not edit by hand\n")
    for k, v in M.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(json.dumps(out, indent=1))
